const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('assets/app.js', 'utf8');
const ctx = {historyItemRowHtml:(g,server)=>`[${g.key}:${server}]`};
vm.createContext(ctx);
vm.runInContext(source.slice(source.indexOf('  function historyCategoryIcon('),source.indexOf('  function renderHistoryItemView(')),ctx);
const groups = [{key:'i-new',category:'item'},{key:'o',category:'other'},{key:'z1',category:'zeny'},{key:'i-old',category:'item'},{key:'z2',category:'zeny'}];
const html = ctx.historyCategoryRowsHtml(groups,true);
assert.ok(html.indexOf('[z1:true]') < html.indexOf('[i-new:true]'));
assert.ok(html.indexOf('[i-new:true]') < html.indexOf('[i-old:true]'));
assert.ok(html.indexOf('[i-old:true]') < html.indexOf('[o:true]'));
assert.equal((html.match(/<h3 /g)||[]).length,3);
assert.equal((html.match(/\[.*?:true\]/g)||[]).length,5,'No merging or lost server groups');
assert.equal(ctx.historyCategoryRowsHtml([],false),'');
assert.equal((ctx.historyCategoryRowsHtml([groups[0]],false).match(/<h3 /g)||[]).length,1);
assert.ok(source.includes("historyCategoryRowsHtml(soldOut, showServer, 'sold')"));
assert.ok(source.includes('historyCategoryRowsHtml(active, showServer)'));
console.log('PASS: category order, newest order within category, all-server preservation, empty/filter and sold grouping');
